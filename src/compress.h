#pragma once

#include <stdbool.h>

/*  Сжимает файл inputPath и записывает результат в outputPath.

Формат архива:
[8 байт]  размер исходного файла (uint64_t, little-endian)
[биты]    сериализованное дерево Хаффмана (preorder)
[биты]    сжатые данные
[биты]    дополнение нулями до границы байта

Пустой файл: записывается только размер 0, дерево и данные отсутствуют.
Результат сначала пишется во временный файл и подменяет outputPath только после успеха,
поэтому при ошибке существующий файл назначения не изменяется.
Возвращает true при успехе, false при любой ошибке (невозможность открыть файл, нехватка памяти, ошибка записи).
*/
bool compressFile(const char* inputPath, const char* outputPath);
