#pragma once

#include "bitStream.h"
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

typedef struct Node Node;

// Таблица частот: количество вхождений каждого байта (0..255) во входных данных
typedef size_t FrequencyTable[256];

// Таблица кодов для всех 256 возможных байтовых значений; представление скрыто в .c
typedef struct CodeTable CodeTable;

// ---Узлы дерева:---
// Создаёт лист для символа symbol с частотой frequency. NULL при ошибке malloc.
Node* createLeaf(uint8_t symbol, size_t frequency);

/* Создаёт внутренний узел, объединяющий left и right; частота = сумма частот
потомков. NULL при ошибке malloc или если left/right равны NULL (left и right
в этом случае не освобождаются - вызывающий код отвечает за них сам). */
Node* createInternal(Node* left, Node* right);

// Рекурсивно освобождает узел и всех его потомков. NULL-указатель безопасен.
void freeNode(Node* node);

// true, если node - лист (хранит символ), false - если внутренний узел
bool isLeaf(const Node* node);
// Символ листа; для внутреннего узла результат не определён
uint8_t getSymbol(const Node* node);
// Левый потомок внутреннего узла; для листа - NULL
Node* getLeft(const Node* node);
// Правый потомок внутреннего узла; для листа - NULL
Node* getRight(const Node* node);

// Частота узла (для листа - исходная частота символа, для внутреннего - сумма потомков)
size_t getFrequency(const Node* node);
// Увеличивает частоту узла на 1
void incrementFrequency(Node* node);

// Индекс узла в массиве кучи приоритетной очереди; используется только PriorityQueue
size_t getHeapIndex(const Node* node);
void setHeapIndex(Node* node, size_t index);

// ---- Построение дерева и таблицы кодов ----

/* Строит дерево Хаффмана по таблице частот, используя приоритетную очередь
(мин-кучу по частоте). Символы с нулевой частотой игнорируются.
Возвращает:
  - NULL, если во входных данных нет ни одного символа (все частоты нулевые)
    или при ошибке выделения памяти;
  - для единственного встретившегося символа возвращает сам лист без
    оборачивания - дерево в этом случае состоит из одного узла, и обычный
    обход не порождает для него кода (код для этого случая явно фиксируется
    в huffmanBuildCodeTable). */
Node* huffmanBuildTree(const FrequencyTable frequencies);

// Освобождает дерево целиком (эквивалентно freeNode(root))
void huffmanFreeTree(Node* root);

/* Строит таблицу кодов обходом дерева: левому переходу соответствует бит 0,
правому - 1, код символа - путь от корня до соответствующего листа. Длина
кода для символов, отсутствующих в дереве, равна 0.
Вырожденный случай: если дерево состоит из одного листа (во входных данных
встретился единственный уникальный байт), обычный обход не даёт коду ни
одного бита, поэтому для такого символа явно фиксируется код длиной 1 бит
(значение бита - 0).
Возвращает NULL, если root == NULL, при ошибке выделения памяти, или если
глубина дерева превысила внутренний предел на длину кода. */
CodeTable* huffmanBuildCodeTable(const Node* root);

// Освобождает таблицу кодов. NULL-указатель безопасен.
void huffmanFreeCodeTable(CodeTable* table);

// Длина кода символа в битах; 0, если символ отсутствует в дереве
uint16_t getCodeLength(const CodeTable* table, uint8_t symbol);

/* i-й бит кода символа (0 или 1), считая от корня дерева. index должен быть
меньше значения, возвращённого getCodeLength для того же символа. */
int getCodeBit(const CodeTable* table, uint8_t symbol, uint16_t index);

// ---Сериализация дерева (для заголовка сжатого файла):---
/* Записывает структуру дерева в битовый поток в порядке preorder:
для листа - бит 1, затем 8 бит символа (от старшего к младшему);
для внутреннего узла - бит 0, затем рекурсивно левое и правое поддерево.
Возвращает false при ошибке записи или если root/writer равны NULL. */
bool huffmanWriteTree(const Node* root, BitWriter* writer);

/* Восстанавливает дерево, ранее записанное huffmanWriteTree.
Возвращает NULL при ошибке чтения, нехватке памяти или если reader == NULL
(частично построенное дерево в этом случае освобождается). */
Node* huffmanReadTree(BitReader* reader);
