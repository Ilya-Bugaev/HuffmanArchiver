/* Разжимает файл inputPath (архив Хаффмана) и записывает результат в outputPath.

Ожидаемый формат архива (создаётся модулем compress):
[8 байт]  размер исходного файла (uint64_t, little-endian)
[биты]    сериализованное дерево Хаффмана (preorder)
[биты]    сжатые данные
[биты]    дополнение нулями до границы байта (игнорируется)

Пустой архив: размер 0, дерево и данные отсутствуют; создаётся пустой файл.
Возвращает true при успехе, false при любой ошибке (невозможность открыть файл, повреждённый архив, нехватка памяти) */
bool decompressFile(const char* inputPath, const char* outputPath);